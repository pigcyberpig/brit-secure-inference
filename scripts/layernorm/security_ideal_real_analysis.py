"""
理想/现实范式 (Ideal/Real Paradigm) 安全性分析
——MLFormer inv_sqrt 协议

核心问题：协议能否在标准模拟安全 (simulation-based security) 下被证明？
"""
import numpy as np


def analyze():
    print("=" * 80)
    print("理想/现实范式安全性分析")
    print("=" * 80)

    # =========================================================================
    print("""
1. 协议回顾
────────────────────────────────────────────────────────────────────────────────
  Input:  [X] (variance, 秘密共享)
  Output: [Y] = [1/√(X+eps)] (秘密共享)

  步骤:
    (1) Party 0 生成 Z ∈ {1,...,255}, 分享 [Z] 和 [Z²]
    (2) [W] = [X+eps] × [Z²]         ← 1 次 Beaver 乘法
    (3) Reveal W                      ← 双方都看到 W!
    (4) [Y] = [Z] × (1/√W)           ← 明文 × 密文, 无通信
""")

    # =========================================================================
    print("""
2. 理想世界 vs 现实世界
────────────────────────────────────────────────────────────────────────────────
  理想世界 (Ideal):
    - 可信第三方 TTP 接收 [X], 计算 Y = 1/√(X+eps), 返回 [Y]
    - 双方仅看到各自的 share, 不看到任何中间值
    - 安全目标: 任何一方的 view 应该可以从 (自己的 input share, output share) 模拟

  现实世界 (Real):
    - 双方执行协议
    - Party 0 的 view: share_0(X), Z, W, share_0(Y)
    - Party 1 的 view: share_1(X), share_1(Z), share_1(Z²), W, share_1(Y)
""")

    # =========================================================================
    print("""
3. Party 0 (Z 生成方) 的安全性分析
────────────────────────────────────────────────────────────────────────────────
  Party 0 明文知道 Z。Reveal W 后:

      X = W / Z² - eps    ← Party 0 直接计算出 X 的精确值!

  理想世界中 Party 0 只知道 share_0(Y), 不知道 X。
  现实世界中 Party 0 完全恢复了 X。

  模拟器 S_0 的困境:
    - S_0 只有 share_0(X) 和 share_0(Y)
    - share_0(Y) 是随机 share, 不含 Y 的信息
    - S_0 无法产生一致的 (Z', W') 使得 Z'/√W' 对应正确的 Y
    - 因为 S_0 根本不知道 Y 的值

  结论: ❌ 对 Party 0 不可模拟, 安全性证明失败
         这不是 z_bits 的问题 —— 即使 z_bits=64, Party 0 知道 Z 就能恢复 X
""")

    # =========================================================================
    print("""
4. Party 1 (非 Z 生成方) 的安全性分析
────────────────────────────────────────────────────────────────────────────────
  Party 1 不知道 Z, 只看到 W = X × Z²。

  模拟器 S_1 需要产生 W' 使得:
    - W' 的分布 ≈ W 的真实分布
    - S_1 只有 share_1(X) 和 share_1(Y)

  对比 Beaver 乘法 (标准 GMW):
    - e = x - a (a 是均匀随机) → e 是均匀随机的 → 完美可模拟
    - f = y - b (b 是均匀随机) → f 是均匀随机的 → 完美可模拟

  MLFormer 的情况:
    - W = X × Z², Z ∈ {1,...,255}
    - W 不是均匀分布!
    - W 的分布取决于 X: P(W=w | X) = 1/255 × 1(w=X×z² for some z)
    - 两个不同的 X₁, X₂ 给出不同的 W 分布
    - S_1 不知道 X, 无法采样出正确分布的 W'
""")

    # =========================================================================
    print("  信息论度量: 不同 X 值下 W 分布的统计距离")
    print()

    Z_max = 255
    z_sq_values = sorted(set(z*z for z in range(1, Z_max+1)))

    x_pairs = [(1.0, 1.1), (1.0, 2.0), (0.1, 1.0), (0.01, 0.1)]
    print(f"  {'X₁':>6} {'X₂':>6} {'SD(W|X₁, W|X₂)':>18}  判定")
    print(f"  {'-'*40}")

    for x1, x2 in x_pairs:
        # W distributions for X1 and X2
        w_dist = {}
        for z in range(1, Z_max + 1):
            w1 = round(x1 * z * z, 8)
            w2 = round(x2 * z * z, 8)
            w_dist[w1] = w_dist.get(w1, 0) + 1/Z_max * 0.5
            w_dist[w2] = w_dist.get(w2, 0) - 1/Z_max * 0.5
        sd = sum(abs(v) for v in w_dist.values())
        verdict = "可区分" if sd > 0.01 else "≈不可区分"
        print(f"  {x1:>6.2f} {x2:>6.2f} {sd:>18.6f}  {verdict}")

    print()
    print("""
  统计距离 SD ≈ 1.0 → 任意两个不同的 X 值产生几乎完全不相交的 W 分布
  → adversary 可以用 W 几乎完美地区分 X₁ 和 X₂
  → W 泄露了 X 的大量信息
  → ❌ 不可模拟
""")

    # =========================================================================
    print("""
5. 根本原因: Z 的值域太小
────────────────────────────────────────────────────────────────────────────────
  标准密码学掩码要求: 掩码必须在整个有限域上均匀分布

  Beaver 乘法: e = x - a, a 均匀分布于 𝔽_p (p ≈ 2⁶⁴)
    → e 均匀分布于 𝔽_p → 完美掩码 → 可模拟 ✓

  MLFormer: W = X × Z², Z ∈ {1,...,255}
    → W 只取 255 个离散值 → 掩码不充分 → 不可模拟 ✗

  理论上, 如果 Z 均匀分布于 𝔽_p:
    → W = X × Z² 均匀分布于 𝔽_p → 完美掩码 → 可模拟 ✓
    → 这就是原始 MLFormer 论文的设计!

  但 CrypTen 定点数溢出约束:
    precision_bits=16, int64 编码
    → X × Z² < 2³¹ ≈ 2.15×10⁹
    → Z² < 6.5×10⁴
    → z_bits ≤ 8
    → 与理想安全性 (Z 均匀于 2⁶⁴) 差距巨大
""")

    # =========================================================================
    print("""
6. 结论
────────────────────────────────────────────────────────────────────────────────
  ┌─────────────────┬────────────────────────┬──────────────────────────────┐
  │                 │ 原始 MLFormer (理论)    │ 当前实现 (z_bits=8)          │
  ├─────────────────┼────────────────────────┼──────────────────────────────┤
  │ Z 分布          │ 均匀于 𝔽_p (p ≈ 2⁶⁴) │ 均匀于 {1,...,255}           │
  │ Party 0 安全性  │ ❌ Party 0 知道 Z      │ ❌ Party 0 知道 Z            │
  │ Party 1 安全性  │ ✓ W 均匀, 可模拟       │ ❌ W 取 255 值, 不可模拟     │
  │ 模拟安全        │ 半可证明*              │ ✗ 不可证明                   │
  └─────────────────┴────────────────────────┴──────────────────────────────┘

  * 原始 MLFormer 理论: 如果 Z 由 TTP 生成且 Z 均匀于 𝔽_p, 则对 Party 1 可证明安全
    但 Party 0 (Z 生成方) 始终能恢复 X, 这是协议结构决定的

  当前实现的双重问题:
    (a) Party 0 生成 Z → Party 0 知道 Z → Party 0 恢复 X    [协议结构问题]
    (b) Z ∈ {1,...,255} → W 不均匀 → Party 1 也泄露 X 信息   [实现约束问题]
""")


if __name__ == "__main__":
    analyze()
